package pl.ggretro.android.data

import java.io.InputStream

/**
 * GG 6 sends text in CP1250, which has no emoji: a keyboard emoji would arrive as "?".
 * Common emoji become the original GG emoticon codes (shown as GG GIFs on both sides), the rest
 * become their Polish name in parentheses, e.g. "(głowa jednorożca)".
 */
class EmojiConverter(private val names: Map<String, String>) {

    data class Result(val text: String, val cursor: Int)

    /** Converts every emoji in [text]; [cursor] is mapped to the same place in the result. */
    fun convert(text: String, cursor: Int = text.length): Result {
        val out = StringBuilder(text.length)
        var newCursor = -1
        var i = 0
        while (i < text.length) {
            if (i == cursor) newCursor = out.length
            val end = clusterEnd(text, i)
            if (end > i) {
                val cluster = text.substring(i, end)
                out.append(replacement(cluster))
                // A cursor inside the emoji lands after its replacement.
                if (cursor in (i + 1) until end) newCursor = out.length
                i = end
            } else {
                out.append(text[i])
                i++
            }
        }
        if (newCursor < 0) newCursor = out.length
        return Result(out.toString(), newCursor)
    }

    fun convert(text: String): String = convert(text, text.length).text

    /** Replacement for one emoji cluster: GG code, else Polish name, else "(emotka)". */
    fun replacement(cluster: String): String {
        val key = cluster.filterNot { it == VS16 || it == VS15 }
        val base = stripModifiers(key)
        GG_CODES[key]?.let { return it }
        GG_CODES[base]?.let { return it }
        val name = names[key] ?: names[base] ?: names[firstCodePoint(base)]
        return "(${name ?: "emotka"})"
    }

    companion object {
        private const val VS16 = '️'
        private const val VS15 = '︎'
        private const val ZWJ = 0x200D
        private const val KEYCAP = 0x20E3

        /** Loads names from the "emoji\tname" TSV generated by tools/make_emoji_names.py. */
        fun load(input: InputStream): EmojiConverter {
            val names = HashMap<String, String>()
            input.bufferedReader(Charsets.UTF_8).useLines { lines ->
                for (line in lines) {
                    if (line.isEmpty() || line.startsWith("#")) continue
                    val tab = line.indexOf('\t')
                    if (tab > 0) names[line.substring(0, tab)] = line.substring(tab + 1)
                }
            }
            return EmojiConverter(names)
        }

