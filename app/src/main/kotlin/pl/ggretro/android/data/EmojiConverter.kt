        private fun isModifier(cp: Int) =
            cp in 0x1F3FB..0x1F3FF || cp == VS16.code || cp == VS15.code || cp in 0xE0020..0xE007F

        private fun stripModifiers(s: String): String {
            val sb = StringBuilder()
            var i = 0
            while (i < s.length) {
                val cp = s.codePointAt(i)
                if (!isModifier(cp)) sb.appendCodePoint(cp)
                i += Character.charCount(cp)
            }
            return sb.toString()
        }

        private fun firstCodePoint(s: String): String =
            if (s.isEmpty()) s else String(Character.toChars(s.codePointAt(0)))

        /** Code points that start an emoji (pictographs outside CP1250). */
        private fun isEmojiStart(cp: Int): Boolean =
            cp >= 0x1F000 && cp <= 0x1FAFF ||
                cp in 0x2600..0x27BF ||
                cp in 0x2300..0x23FF ||
                cp in 0x2B00..0x2BFF ||
                cp in 0x2190..0x21FF ||
                cp in 0x25A0..0x25FF ||
                cp in 0x2900..0x297F ||
                cp == 0x203C || cp == 0x2049 || cp == 0x2139 || cp == 0x24C2 ||
                cp == 0x3030 || cp == 0x303D || cp == 0x3297 || cp == 0x3299

        /**
         * End index of the emoji cluster starting at [start], or [start] if none starts there.
         * Handles variation selectors, skin tones, ZWJ sequences, flags, tags and keycaps.
         */
        fun clusterEnd(text: String, start: Int): Int {
            val first = text.codePointAt(start)
            var i = start + Character.charCount(first)
            // Keycap: [0-9#*] FE0F? 20E3
            if (first == '#'.code || first == '*'.code || first in '0'.code..'9'.code) {
                var j = i
                if (j < text.length && text[j] == VS16) j++
                return if (j < text.length && text[j].code == KEYCAP) j + 1 else start
            }
            // Flag: two regional indicators.
            if (first in 0x1F1E6..0x1F1FF) {
                if (i < text.length) {
                    val next = text.codePointAt(i)
                    if (next in 0x1F1E6..0x1F1FF) return i + Character.charCount(next)
                }
                return i
            }
            if (!isEmojiStart(first)) return start
            while (i < text.length) {
                val cp = text.codePointAt(i)
                when {
                    isModifier(cp) || cp == KEYCAP -> i += Character.charCount(cp)
                    cp == ZWJ && i + 1 < text.length -> {
                        val next = text.codePointAt(i + 1)
                        i += 1 + Character.charCount(next)
                    }
                    else -> return i
                }
            }
            return i
        }
    }
}
